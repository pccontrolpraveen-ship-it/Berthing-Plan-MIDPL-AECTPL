/* PORTVISION 3D — single-file build.
 *
 * Inlines styles.css, the vendored Three.js and app.js into one .html that
 * opens with a double click, no server and no unpacking. Intended for sending
 * the application to someone to look at; the real builds are www/ (browser and
 * PWA), desktop/ (Electron) and android/ + ios/ (Capacitor).
 *
 *   node tools/make-standalone.js  →  dist/portvision-3d-standalone.html
 *
 * The result always runs in Standalone mode: opened from disk there is no
 * origin to reach a PortVision server from, so it stores plans in that
 * browser's storage and says so in the top bar.
 */
const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const WWW = path.join(ROOT, 'www');
const OUT_DIR = path.join(ROOT, 'dist');
const OUT = path.join(OUT_DIR, 'portvision-3d-standalone.html');

/* --artifact additionally writes a variant for a host that supplies its own
   document skeleton, so the fragment carries no <html>, <head> or <body> of its
   own — nested ones would be dropped by the parser and take the app's layout
   with them. */
const ARTIFACT = process.argv.includes('--artifact');
const OUT_ARTIFACT = path.join(OUT_DIR, 'portvision-3d-artifact.html');

const read = f => fs.readFileSync(path.join(WWW, f), 'utf8');

/* A literal </script> anywhere inside inlined JavaScript would close the tag
   early and dump the rest of the file into the page as text. */
const safeJs = js => js.replace(/<\/script>/gi, '<\\/script>');

let html = read('index.html');

/* Stylesheet */
html = html.replace(
  '<link rel="stylesheet" href="styles.css">',
  '<style>\n' + read('styles.css') + '\n</style>');

/* Three.js — the whole point of vendoring it is that this works with no network */
html = html.replace(
  '<script src="vendor/three.min.js"></script>',
  '<script>\n' + safeJs(read('vendor/three.min.js')) + '\n</script>');

/* Application */
html = html.replace(
  '<script src="app.js"></script>',
  '<script>\n' + safeJs(read('app.js')) + '\n</script>');

/* Progressive-web-app plumbing has nothing to attach to in a single file: a
   service worker cannot register from file://, and the manifest and icon files
   are not alongside it. pwa.js already disables itself, but referencing files
   that are not there would still log misleading 404s. */
html = html
  .replace('<script src="pwa.js"></script>', '')
  .replace('<link rel="manifest" href="manifest.webmanifest">', '')
  .replace(/<link rel="icon"[^>]*>\n?/, '')
  .replace(/<link rel="apple-touch-icon"[^>]*>\n?/, '');

/* Keep a tab icon by embedding it rather than linking it. */
const favicon = fs.readFileSync(path.join(WWW, 'icons', 'icon-192.png')).toString('base64');
html = html.replace('</head>',
  `<link rel="icon" type="image/png" href="data:image/png;base64,${favicon}">\n</head>`);

html = html.replace('<head>',
  `<head>\n<!-- PORTVISION 3D — single-file build generated by tools/make-standalone.js.\n` +
  `     Do not edit: change www/ and regenerate. -->`);

fs.mkdirSync(OUT_DIR, { recursive: true });
fs.writeFileSync(OUT, html);

if (ARTIFACT) {
  /* Strip the document wrapper. The title survives as a bare element — the host
     reads it for the tab and gallery name — and the stylesheet keeps painting
     body itself, so the application still owns the viewport. */
  let frag = html
    .replace(/<!DOCTYPE[^>]*>\s*/i, '')
    .replace(/<html[^>]*>\s*/i, '').replace(/<\/html>\s*/i, '')
    .replace(/<head>\s*/i, '').replace(/<\/head>\s*/i, '')
    .replace(/<body[^>]*>\s*/i, '').replace(/<\/body>\s*/i, '')
    .replace(/<meta[^>]*>\s*/gi, '')
    .replace(/<link rel="icon"[^>]*>\s*/i, '');

  /* The host scans only the first 8 KB for a title, and the inlined Three.js is
     600 KB, so the title has to lead. */
  frag = frag.replace(/<title>[^<]*<\/title>\s*/i, '');
  frag = '<title>PORTVISION 3D</title>\n' + frag;

  fs.mkdirSync(OUT_DIR, { recursive: true });
  fs.writeFileSync(OUT_ARTIFACT, frag);

  /* Check the markup only. app.js builds a printable report with
     document.write('<html>…'), and that string is not a document wrapper. */
  const markupOnly = frag
    .replace(/<script[\s\S]*?<\/script>/gi, '')
    .replace(/<style[\s\S]*?<\/style>/gi, '');
  const bad = /<(!DOCTYPE|html|head|body)[\s>]/i.exec(markupOnly);
  if (bad) throw new Error('document wrapper survived stripping: ' + bad[0]);
  console.log('wrote', path.relative(ROOT, OUT_ARTIFACT), '—',
    (Buffer.byteLength(frag) / 1024).toFixed(0) + ' KB (fragment)');
}

const kb = n => (n / 1024).toFixed(0) + ' KB';
console.log('wrote', path.relative(ROOT, OUT), '—', kb(Buffer.byteLength(html)));
for (const f of ['styles.css', 'vendor/three.min.js', 'app.js']) {
  console.log('  inlined', f.padEnd(22), kb(fs.statSync(path.join(WWW, f)).size));
}
